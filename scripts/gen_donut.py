#!/usr/bin/env python3
"""Generate examples/donut.sel: a fully rendered polygonal torus in selenium.

Computed in-language: cos/sin builtins over a ring/tube parameterisation,
per-frame spin about X plus fixed tilt about Y, rotated-normal Lambert
shading redirected into an opacity band, orthographic projection, and
alpha-filled SVG polygons as a filmstrip. whisper prints terminate with
newlines, which SVG accepts as whitespace in point lists and attributes.
"""

import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

R, TUBE = 3.0, 1.25
RING, TUBE_N = 16, 10
SCALE, OY = 28.0, 130.0
FRAMES = 4
TILT = 0.72
SPIN = 0.62
LIGHT = (0.32, 0.58, 0.75)
COL_W = 260
CB, SB = round(math.cos(TILT), 12), round(math.sin(TILT), 12)

TH_STEP = round(2 * math.pi / RING, 12)
PH_STEP = round(2 * math.pi / TUBE_N, 12)

CORNERS = (
    ("cp1", "sp1", "ct1", "st1"),
    ("cp2", "sp2", "ct1", "st1"),
    ("cp2", "sp2", "ct2", "st2"),
    ("cp1", "sp1", "ct2", "st2"),
)

lines = []


def emit(s=""):
    lines.append(s)


emit("// Generated by scripts/gen_donut.py: a polygonal torus filmstrip in SVG.")
emit("// Computed in-language with cos/sin, spin+tilt rotation, and per-quad")
emit("// rotated-normal shading emitted as alpha-filled polygons.")
emit("wax float cb = {};".format(CB))
emit("wax float sb = {};".format(SB))
emit("wax float thstep = {};".format(TH_STEP))
emit("wax float phstep = {};".format(PH_STEP))
for name in (
    "ca",
    "sa",
    "ct1",
    "st1",
    "ct2",
    "st2",
    "cp1",
    "sp1",
    "cp2",
    "sp2",
    "nx",
    "ny",
    "nz",
    "u",
    "rad",
    "x",
    "y",
    "z",
    "cy",
    "cz",
):
    emit("wax float {} = 0.0;".format(name))
emit(
    "whisper \"<svg xmlns=\\'http://www.w3.org/2000/svg\\' width=\\'{}\\' height=\\'270\\'>\";".format(
        FRAMES * COL_W
    )
)

if True:
    frame = 0
    emit()
    emit("orbit (wax int f = 0; f < {}; f = f + 1) {{".format(FRAMES))
    emit("    ca = cos(0.62 * f);")
    emit("    sa = sin(0.62 * f);")
    emit("    orbit (wax int i = 0; i < 16; i = i + 1) {")
    emit("        ct1 = cos(i * thstep);")
    emit("        st1 = sin(i * thstep);")
    emit("        ct2 = cos((i + 1) * thstep);")
    emit("        st2 = sin((i + 1) * thstep);")
    emit("        orbit (wax int j = 0; j < 10; j = j + 1) {")
    emit("            cp1 = cos(j * phstep);")
    emit("            sp1 = sin(j * phstep);")
    emit("            cp2 = cos((j + 1) * phstep);")
    emit("            sp2 = sin((j + 1) * phstep);")
    emit("            ny = sp1 * ca - cp1 * st1 * sa;")
    emit("            nz = sp1 * sa + cp1 * st1 * ca;")
    emit("            nx = cp1 * ct1 * cb + nz * sb;")
    emit(
        "            u = 0.18 + 0.30 * (nx * {} + ny * {} + nz * {} + 1.0);".format(
            *LIGHT
        )
    )
    emit('            whisper "<polygon points=\'";')
    for n, (cp, sp, ct, st) in enumerate(CORNERS):
        emit("            rad = {} + {} * {};".format(R, TUBE, cp))
        emit("            x = rad * {};".format(ct))
        emit("            y = {} * {};".format(TUBE, sp))
        emit("            z = rad * {};".format(st))
        emit("            cy = y * ca - z * sa;")
        emit("            cz = y * sa + z * ca;")
        emit(
            "            whisper (x * cb + cz * sb) * {} + {} + f * {};".format(
                SCALE, OY, COL_W
            )
        )
        emit('            whisper ",";')
        emit("            whisper {} - cy * {};".format(OY, SCALE))
        if n < len(CORNERS) - 1:
            emit('            whisper " ";')
    emit("            whisper \"' fill='#6b4432' fill-opacity='\";")
    emit("            whisper u;")
    emit('            whisper "\'/>";')
    emit("        };")
    emit("    };")
    emit("};")
emit('whisper "</svg>";')

text = "\n".join(lines) + "\n"
(ROOT / "examples" / "donut.sel").write_text(text, encoding="utf-8")
print("wrote examples/donut.sel: {} lines".format(len(text.splitlines())))
