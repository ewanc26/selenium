#!/usr/bin/env python3
"""Generate examples/donut_engine.sel: a live polygonal torus streaming shaded
quads to the SDL2 host in host/donut_host.c.

Token protocol (whitespace-separated; whisper prints end with newlines, which
are whitespace to the host's scanf loop):

    F                              begin frame
    P x1 y1 x2 y2 x3 y3 x4 y4 r g b  shaded quad, window coordinates
    S                              swap/present

The program computes the animation live in-language: nested orbits over
RING x TUBE_N quads, spin +0.05 per frame, TILT = 0.72, orthographic camera
projection and per-quad rotated-normal Lambert shading. It emits a finite
FRAMES-long stream and exits; the host replays the recorded frames forever,
so the demo still animates, and a finite producer lets the host (which reads
the whole stream before presenting) terminate under ``--frames N``.

Pipeline:

    ./build/seleniumc examples/donut_engine.sel --run --cc clang \\
        | ./build/donut_host --frames 3
"""

import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

R, TUBE = 3.0, 1.25
RING, TUBE_N = 16, 10
FRAMES = 40
SPIN_STEP = 0.05
TILT = 0.72
SCALE, OX, OY = 28.0, 120.0, 120.0
LIGHT = (0.32, 0.58, 0.75)
TH_STEP = round(2 * math.pi / RING, 12)
PH_STEP = round(2 * math.pi / TUBE_N, 12)
CB, SB = round(math.cos(TILT), 12), round(math.sin(TILT), 12)

CORNERS = (
    ("cp1", "sp1", "ct1", "st1"),
    ("cp2", "sp2", "ct1", "st1"),
    ("cp2", "sp2", "ct2", "st2"),
    ("cp1", "sp1", "ct2", "st2"),
)

lines = []


def emit(s=""):
    lines.append(s)


emit("// Generated by scripts/gen_donut_engine.py: a live spinning torus")
emit("// streaming F/P/S tokens to host/donut_host.c (SDL2).")
emit("// Run: ./build/seleniumc examples/donut_engine.sel --run --cc clang")
emit("//          | ./build/donut_host --frames 3   (SDL_VIDEODRIVER=dummy works)")
emit("wax float cb = {};".format(CB))
emit("wax float sb = {};".format(SB))
emit("wax float thstep = {};".format(TH_STEP))
emit("wax float phstep = {};".format(PH_STEP))
for name in (
    "ca",
    "sa",
    "ct1",
    "st1",
    "ct2",
    "st2",
    "cp1",
    "sp1",
    "cp2",
    "sp2",
    "nx",
    "ny",
    "nz",
    "lum",
    "cr",
    "cg",
    "colb",
    "rad",
    "x",
    "y",
    "z",
    "cy",
    "cz",
):
    emit("wax float {} = 0.0;".format(name))

emit("orbit (wax int f = 0; f < {}; f = f + 1) {{".format(FRAMES))
emit("    ca = cos({} * f);".format(SPIN_STEP))
emit("    sa = sin({} * f);".format(SPIN_STEP))
emit('    whisper "F";')
emit("    orbit (wax int i = 0; i < {}; i = i + 1) {{".format(RING))
emit("        ct1 = cos(i * thstep);")
emit("        st1 = sin(i * thstep);")
emit("        ct2 = cos((i + 1) * thstep);")
emit("        st2 = sin((i + 1) * thstep);")
emit("        orbit (wax int j = 0; j < {}; j = j + 1) {{".format(TUBE_N))
emit("            cp1 = cos(j * phstep);")
emit("            sp1 = sin(j * phstep);")
emit("            cp2 = cos((j + 1) * phstep);")
emit("            sp2 = sin((j + 1) * phstep);")
emit("            ny = sp1 * ca - cp1 * st1 * sa;")
emit("            nz = sp1 * sa + cp1 * st1 * ca;")
emit("            nx = cp1 * ct1 * cb + nz * sb;")
emit("            lum = (nx * {} + ny * {} + nz * {} + 1.0) * 0.5;".format(*LIGHT))
emit("            cr = 150.0 * lum + 80.0;")
emit("            cg = 90.0 * lum + 50.0;")
emit("            colb = 60.0 * lum + 30.0;")
emit('            whisper "P";')
for cp, sp, ct, st in CORNERS:
    emit("            rad = {} + {} * {};".format(R, TUBE, cp))
    emit("            x = rad * {};".format(ct))
    emit("            y = {} * {};".format(TUBE, sp))
    emit("            z = rad * {};".format(st))
    emit("            cy = y * ca - z * sa;")
    emit("            cz = y * sa + z * ca;")
    emit("            whisper (x * cb + cz * sb) * {} + {};".format(SCALE, OX))
    emit("            whisper {} - cy * {};".format(OY, SCALE))
emit("            whisper cr;")
emit("            whisper cg;")
emit("            whisper colb;")
emit("        };")
emit("    };")
emit('    whisper "S";')
emit("};")

text = "\n".join(lines) + "\n"
(ROOT / "examples" / "donut_engine.sel").write_text(text, encoding="utf-8")
print(
    "wrote examples/donut_engine.sel: {} lines, {} frames x {} quads".format(
        len(text.splitlines()), FRAMES, RING * TUBE_N
    )
)
