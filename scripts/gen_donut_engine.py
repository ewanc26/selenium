#!/usr/bin/env python3
"""Generate examples/donut_engine.sel: a live orbiting-light torus streaming a
per-frame vertex list to the SDL2 host in host/donut_host.c.

Protocol v2 (whitespace-separated; whisper prints end with newlines, which are
whitespace to the host's scanf loop):

    F                       begin frame
    px py z intensity       one VERTEX: four %g numbers per vertex, printed
                            one per line, 1500 vertices per frame in i*30+j
                            order (50 ring steps x 30 tube steps)
    S                       swap/present

The host (a faithful port of the reference doughnut.c renderer) builds the
triangle mesh in-host and rasterizes the recorded vertex frames.

The engine mirrors doughnut.c's float32 pipeline EXACTLY:

* every arithmetic variable is `wax single` (a C float), so each statement is a C float
  assignment and every operation folds to single precision at each
  intermediate, exactly like doughnut.c's float expressions;
* every constant lives in a `wax single` (a C float) variable, folding to the float32
  constant C computes from `0.025f`/`0.8f`/... at initialisation (a bare
  `1.0` in an expression would be a C double literal and promote the
  whole sub-expression to double);
* trig and sqrt run through the summoned C functions cosf/sinf/sqrtf
  (math.h is pre-included by the emitter), so they are correctly rounded
  to float32 exactly like doughnut.c's;
* u and v are computed as doughnut.c's `((float)i / 50.0f * 2.0f) * M_PI`:
  the float fold happens through the float constant variables, and the
  final multiply by the double `dpi` (M_PI) promotes to double and folds
  back to float at the assignment, exactly like C;
* angleX = angleY = 0.5 via cosf/sinf(0.5f) (the k05 variable), angleZ
  accumulating +0.003 after each rendered frame, light_angle accumulating
  +0.025 before each computation, light_pos = (cosf(la)*4.5f, sinf(la)*4.5f,
  sinf(la*0.7f)*2.5f), projection px = (rpx/camz)*500f + 400f, py =
  (rpy/camz)*500f + 300f, and intensity = max(dot(rot_normal,
  unit(light-pos)), 0.08f) / (1.0f + 0.04f*dist) with rotation X then Y
  then Z and per-operation float32 folding in the reference's exact
  arithmetic order (positions and normals rotate identically).

Numbers print through the summoned donut_num helper (printf %g of the
value promoted to double, which prints the same significant digits the
canonical float32 capture prints), the same format the other language
emitters use; strings go through whisper (puts). The stream is a finite
48-frame prefix of the canonical animation and exits; the host replays the
recorded frames forever and a finite producer keeps the read-the-whole-
stream host pipeline terminating under ``--frames N``.

NOTE: compile the engine's generated C without FMA contraction
(-ffp-contract=off, or unoptimized) or the per-operation float folds
change (do not pipe through an optimizing compiler that contracts).

Pipeline:

    ./build/seleniumc examples/donut_engine.sel --run --cc clang \\
        | ./build/donut_host --frames 3
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

U_STEPS, V_STEPS = 50, 30
FRAMES = 48
M_PI = 3.141592653589793  # repr(math.pi): exactly the double M_PI parses to

lines = []


def emit(s=""):
    lines.append(s)


emit("// Generated by scripts/gen_donut_engine.py: a live orbiting-light torus")
emit("// streaming per-frame vertex lists to host/donut_host.c (SDL2),")
emit("// protocol v2: F, 1500 x (px py z intensity) as %g, S.")
emit("// Mirrors doughnut.c's float32 pipeline: every variable and constant is")
emit("// a C float (per-operation single-precision folds) and trig/sqrt are the")
emit("// C cosf/sinf/sqrtf, exactly like the reference.")
emit('summon ritual donut_num(float v) -> int from "donut_num.c";')
emit("summon ritual cosf(single v) -> single;")
emit("summon ritual sinf(single v) -> single;")
emit("summon ritual sqrtf(single v) -> single;")

# Float32-folded constants: C folds 0.025f, 0.8f, ... exactly once at these
# initialisations, and every later arithmetic stays in float.
consts = {
    "k2": "2.0",  # R_MAJOR and the *2.0f of u/v
    "k08": "0.8",  # R_MINOR
    "k50": "50.0",  # U_STEPS divisor (as float)
    "k30": "30.0",  # V_STEPS divisor (as float)
    "k025": "0.025",  # light_angle step
    "k003": "0.003",  # angleZ step
    "k07": "0.7",  # light z frequency
    "k45": "4.5",  # light orbit radius
    "k25": "2.5",  # light z scale
    "k08f": "0.08",  # ambient floor
    "k004": "0.04",  # attenuation
    "k1": "1.0",
    "ke5": "1e-5",  # normalize threshold
    "k5": "5.0",  # camera_dist
    "kfov": "500.0",  # fov
    "k400": "400.0",  # WIDTH / 2.0f
    "k300": "300.0",  # HEIGHT / 2.0f
    "k05": "0.5",  # angleX = angleY
}
for name, value in consts.items():
    emit("wax single {} = {};".format(name, value))
emit("wax double dpi = {};".format(repr(M_PI)))

# Rotation temporaries carry p/n prefixes: bare y1 collides with math.h's
# Bessel function once the generated C is compiled.
TEMPS = (
    "cax",
    "sax",
    "cay",
    "say",
    "caz",
    "saz",
    "lx",
    "ly",
    "lz",
    "u",
    "cu",
    "su",
    "v",
    "cv",
    "sv",
    "vx",
    "vy",
    "vz",
    "nx0",
    "ny0",
    "nz0",
    "p1x",
    "p1y",
    "p1z",
    "p2x",
    "p2y",
    "p2z",
    "rpx",
    "rpy",
    "rpz",
    "n1x",
    "n1y",
    "n1z",
    "n2x",
    "n2y",
    "n2z",
    "rnx",
    "rny",
    "rnz",
    "ldx",
    "ldy",
    "ldz",
    "dist",
    "inten",
    "camz",
    "px",
    "py",
)
for name in TEMPS:
    emit("wax single {} = 0.0;".format(name))

emit("wax single az = 0.0;")
emit("wax single la = 0.0;")

emit("orbit (wax int f = 0; f < {F}; f = f + 1) {{".format(F=FRAMES))
emit("    la = la + k025;")
emit("    lx = cosf(la) * k45;")
emit("    ly = sinf(la) * k45;")
emit("    lz = sinf(la * k07) * k25;")
emit("    caz = cosf(az);")
emit("    saz = sinf(az);")
emit('    whisper "F";')
emit("    orbit (wax int i = 0; i < {U}; i = i + 1) {{".format(U=U_STEPS))
# u = ((float)i / 50.0f * 2.0f) * M_PI: float folds through k50/k2, the
# double dpi promotes only the final multiply, and the assignment folds
# back to float — doughnut.c's expression exactly.
emit("        u = i / k50 * k2 * dpi;")
emit("        cu = cosf(u);")
emit("        su = sinf(u);")
emit("    orbit (wax int j = 0; j < {V}; j = j + 1) {{".format(V=V_STEPS))
emit("            v = j / k30 * k2 * dpi;")
emit("            cv = cosf(v);")
emit("            sv = sinf(v);")
# Base torus vertex and surface normal (reference generate_torus).
emit("            vx = (k2 + k08 * cv) * cu;")
emit("            vy = (k2 + k08 * cv) * su;")
emit("            vz = k08 * sv;")
emit("            nx0 = cv * cu;")
emit("            ny0 = cv * su;")
emit("            nz0 = sv;")
# Rotate position: X, then Y, then Z (reference rotate_vector order), with
# cosf/sinf(0.5f) inline exactly where the reference calls them.
emit("            p1y = vy * cosf(k05) - vz * sinf(k05);")
emit("            p1z = vy * sinf(k05) + vz * cosf(k05);")
emit("            p1x = vx;")
emit("            p2x = p1x * cosf(k05) + p1z * sinf(k05);")
emit("            p2z = p1z * cosf(k05) - p1x * sinf(k05);")
emit("            p2y = p1y;")
emit("            rpx = p2x * caz - p2y * saz;")
emit("            rpy = p2x * saz + p2y * caz;")
emit("            rpz = p2z;")
# Rotate the normal with the same rotation.
emit("            n1y = ny0 * cosf(k05) - nz0 * sinf(k05);")
emit("            n1z = ny0 * sinf(k05) + nz0 * cosf(k05);")
emit("            n1x = nx0;")
emit("            n2x = n1x * cosf(k05) + n1z * sinf(k05);")
emit("            n2z = n1z * cosf(k05) - n1x * sinf(k05);")
emit("            rnx = n2x * caz - n1y * saz;")
emit("            rny = n2x * saz + n1y * caz;")
emit("            rnz = n2z;")
# Orbiting point light, Lambertian diffuse + ambient floor, attenuation.
emit("            ldx = lx - rpx;")
emit("            ldy = ly - rpy;")
emit("            ldz = lz - rpz;")
emit("            dist = sqrtf(ldx * ldx + ldy * ldy + ldz * ldz);")
emit("            eclipse (dist > ke5) {")
emit("                ldx = ldx / dist;")
emit("                ldy = ldy / dist;")
emit("                ldz = ldz / dist;")
emit("            };")
emit("            inten = rnx * ldx + rny * ldy + rnz * ldz;")
emit("            eclipse (inten < k08f) {")
emit("                inten = k08f;")
emit("            };")
emit("            inten = inten / (k1 + k004 * dist);")
# Camera distance and perspective projection (reference fov 500).
emit("            camz = rpz + k5;")
emit("            px = (rpx / camz) * kfov + k400;")
emit("            py = (rpy / camz) * kfov + k300;")
emit("            donut_num(px);")
emit("            donut_num(py);")
emit("            donut_num(camz);")
emit("            donut_num(inten);")
emit("        };")
emit("    };")
emit('    whisper "S";')
emit("    az = az + k003;")
emit("};")

text = "\n".join(lines) + "\n"
(ROOT / "examples" / "donut_engine.sel").write_text(text, encoding="utf-8")
print(
    "wrote examples/donut_engine.sel: {} lines, {} frames x {} vertices".format(
        len(text.splitlines()), FRAMES, U_STEPS * V_STEPS
    )
)
